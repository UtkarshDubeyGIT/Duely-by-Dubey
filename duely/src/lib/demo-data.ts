export function getDemoDashboardData(): DashboardData {
  const paidThisMonth = demoInvoices
    .filter((invoice) => invoice.status === "paid" && invoice.paid_date?.startsWith("2026-05"))
    .reduce((sum, invoice) => sum + invoice.total_amount, 0);

  return {
    stats: {
      total_invoices: demoInvoices.length,
      unpaid_amount: demoInvoices
        .filter((invoice) => invoice.status === "pending" || invoice.status === "overdue")
        .reduce((sum, invoice) => sum + invoice.total_amount, 0),
      overdue_count: demoInvoices.filter((invoice) => invoice.status === "overdue").length,
      paid_this_month: paidThisMonth,
      total_invoices_trend: 12,
      unpaid_amount_trend: -4,
      overdue_count_trend: 2,
      paid_this_month_trend: 18,
    },
    recent_invoices: demoInvoices.slice(0, 5),
    upcoming_reminders: demoReminderSchedule,
    overdue_invoices: demoInvoices.filter((invoice) => invoice.status === "overdue"),
  };
}
